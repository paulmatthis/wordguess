#!/usr/bin/env python3
"""Builds the game's word data from published word lists (nothing hand-written).

Sources, kept in tools/sources/:
  scowl/        SCOWL 2020.12.07 (wordlist.aspell.net), graded by how common
                words are: size 10 = most common ... 70 = large dictionary.
  enable1.txt   ENABLE, the public-domain dictionary used by word games.

  wordle/       The original Wordle lists: answers.txt (2,315 answers) and
                guesses.txt (the other 10,657 words Wordle accepts).

Output:
  docs/words.js    answers
  docs/dict/N.txt  accepted guesses

5-letter games use the Wordle lists exactly, and nothing else. Wordle has no
lists for other lengths, so 3, 4, 6 and 7 use SCOWL sizes 10-35 for answers
and ENABLE plus SCOWL up to size 70 for accepted guesses.

Only all-lowercase a-z entries are used, which drops proper nouns,
abbreviations and anything with an apostrophe.  Run: python3 tools/build.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "sources")
APP = os.path.join(ROOT, "docs")
LENGTHS = range(3, 8)

ANSWER_SIZES = (10, 20, 35)
ANSWER_SETS = ("english", "american")
GUESS_SIZES = (10, 20, 35, 40, 50, 55, 60, 70)
GUESS_SETS = ("english", "american", "british", "canadian")


def clean(lines):
    return {w for w in (l.strip() for l in lines) if re.fullmatch(r"[a-z]{3,7}", w)}


def scowl(sets, sizes):
    words = set()
    for name in sets:
        for size in sizes:
            path = os.path.join(SRC, "scowl", f"{name}-words.{size}")
            if os.path.exists(path):
                with open(path, encoding="latin-1") as f:
                    words |= clean(f)
    return words


def main():
    answers = scowl(ANSWER_SETS, ANSWER_SIZES)
    with open(os.path.join(SRC, "enable1.txt")) as f:
        valid = clean(f) | scowl(GUESS_SETS, GUESS_SIZES) | answers

    # 5 letters: the Wordle lists replace everything above.
    wordle = {}
    for name in ("answers", "guesses"):
        with open(os.path.join(SRC, "wordle", name + ".txt")) as f:
            wordle[name] = clean(f)
    answers = {w for w in answers if len(w) != 5} | wordle["answers"]
    valid = {w for w in valid if len(w) != 5} | wordle["answers"] | wordle["guesses"]

    os.makedirs(os.path.join(APP, "dict"), exist_ok=True)
    by_len = {n: sorted(w for w in answers if len(w) == n) for n in LENGTHS}
    with open(os.path.join(APP, "words.js"), "w") as f:
        f.write("// Generated by tools/build.py from the lists in tools/sources. Do not edit.\n")
        f.write("const ANSWERS = " + json.dumps(
            {n: " ".join(ws) for n, ws in by_len.items()}, indent=0) + ";\n")

    for n in LENGTHS:
        words = sorted(w for w in valid if len(w) == n)
        with open(os.path.join(APP, "dict", f"{n}.txt"), "w") as f:
            f.write("".join(words))  # fixed width, no separators
        print(f"{n} letters: {len(by_len[n]):5d} answers, {len(words):6d} accepted guesses")


if __name__ == "__main__":
    main()
